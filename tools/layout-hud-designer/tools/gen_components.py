"""Generates the v0 library from tools/kld_tokens.py (D-09: the source of truth is this repo).

Outputs:
  KrydenLayoutHudDesigner_Client/scripts/3_Game/kld/KLD_Tokens.c   ARGB colors + prefab paths (DO NOT EDIT)
  KrydenLayoutHudDesigner_Client/gui/layouts/kld/kld_button.layout
  KrydenLayoutHudDesigner_Client/gui/layouts/kld/kld_button_primary.layout   bold label (D-12)
  KrydenLayoutHudDesigner_Client/gui/layouts/kld/kld_badge.layout
  KrydenLayoutHudDesigner_Client/gui/layouts/kld/kld_badge_primary.layout    bold label (D-12)
  KrydenLayoutHudDesigner_Client/gui/layouts/kld/kld_card.layout
  KrydenLayoutHudDesigner_Client/gui/layouts/kld/kld_separator.layout

Sizes (1920x1080 reference units) come from shadcn/ui with the D-07 type scale (+2 on text):
button h-8 = 32, text-sm 14 -> 16; badge h-5 + text 12 -> height 24 and 14; card
--card-spacing 16, title text-base 16 -> 18, description text-sm 14 -> 16. Radius 10 (D-06); the
web badge is a pill (rounded-4xl) and height 24 with radius 10 is the closest to it.

    python tools/gen_components.py
"""
from pathlib import Path

from kld_layout import W, geo, node, text, write
from kld_tokens import BADGE, BUTTON, TOKENS, _disabled, argb, layout_color

ROOT = Path(__file__).resolve().parent.parent
CLIENT = ROOT / "KrydenLayoutHudDesigner_Client"
PREFIX = "Kryden/KrydenLayoutHudDesigner/KrydenLayoutHudDesigner_Client"
LAYOUT_DIR = CLIENT / "gui" / "layouts" / "kld"
BOOK = "gui/fonts/sdf_MetronBook24"
# D-12: primary label (dark text on a light background) in bold. Vanilla has no bold SDF; MetronBook-Bold
# is a bitmap font: sharp at 1080p and readable at 720p (lab round 7); 1440p/4K not measured.
BOLD16 = "gui/fonts/MetronBook-Bold16"
BOLD14 = "gui/fonts/MetronBook-Bold14"

PREFABS = {
    "BUTTON": "kld_button.layout",
    "BUTTON_PRIMARY": "kld_button_primary.layout",
    "BADGE": "kld_badge.layout",
    "BADGE_PRIMARY": "kld_badge_primary.layout",
    "CARD": "kld_card.layout",
    "SEPARATOR": "kld_separator.layout",
}
FILL = (0, 0, 1, 1, 0, 0, 0, 0)          # fills the whole parent (proportional)


def button_layout(font=BOOK):
    bg, _, fg, border = BUTTON["PRIMARY"]
    attrs = [("visible", 1), ("color", layout_color(bg))] + geo(0, 0, 128, 32) + [("style", "kld_btn_fill_r10")]
    kids = [
        W("Panel", "kld_button_border", [("visible", 0), ("ignorepointer", 1), ("color", layout_color(TOKENS["input"]))]
          + geo(*FILL) + [("style", "kld_ring_r10")]),
        text("kld_button_label", geo(*FILL), "Button", 16, layout_color(fg), font, halign="center"),
    ]
    return node("Button", "kld_button", attrs, kids)


def badge_layout(font=BOOK):
    bg, fg, _ = BADGE["PRIMARY"]
    attrs = [("visible", 1), ("ignorepointer", 1), ("color", layout_color(bg))] + geo(0, 0, 80, 24) + [("style", "kld_fill_r10")]
    kids = [
        W("Panel", "kld_badge_border", [("visible", 0), ("ignorepointer", 1), ("color", layout_color(TOKENS["border"]))]
          + geo(*FILL) + [("style", "kld_ring_r10")]),
        text("kld_badge_label", geo(*FILL), "Badge", 14, layout_color(fg), font, halign="center"),
    ]
    return node("Panel", "kld_badge", attrs, kids)


def card_layout():
    # 16 + title 24 + 8 + description 20 + 16 + content 72 + 16 + footer 32 + 16 = 220
    attrs = [("visible", 1), ("color", layout_color(TOKENS["card"]))] + geo(0, 0, 400, 220) + [("style", "kld_fill_r10")]
    kids = [
        W("Panel", "kld_card_border", [("visible", 1), ("ignorepointer", 1), ("color", layout_color(TOKENS["card_ring"]))]
          + geo(*FILL) + [("style", "kld_ring_r10")]),
        text("kld_card_title", geo(16, 16, 368, 24), "Title", 18, layout_color(TOKENS["foreground"]), BOOK),
        text("kld_card_desc", geo(16, 48, 368, 20), "Description", 16, layout_color(TOKENS["muted_foreground"]), BOOK),
        # no ignorepointer on containers that receive buttons: not measured whether it blocks the children
        W("Frame", "kld_card_content", [("visible", 1)] + geo(16, 84, 368, 72)),
        # footer: buttons side by side with a gap of 8 (Padding = gap, Margin = inset; lab round 1)
        W("WrapSpacer", "kld_card_footer", [("visible", 1)] + geo(16, 16, 368, 32)
          + [("valign", "bottom_ref"), ("Padding", 8), ("Margin", 0)]),
    ]
    return node("Panel", "kld_card", attrs, kids)


def separator_layout():
    # bg-border h-px w-full: parent width, height 1 (1080p unit: 0.67 px at 720p, still renders - lab round 5)
    attrs = [("visible", 1), ("ignorepointer", 1), ("color", layout_color(TOKENS["border"]))] + geo(0, 0, 1, 1, 1, 1, 0, 1) + [("style", "rover_sim_colorable")]
    return node("Panel", "kld_separator", attrs)


def tokens_c():
    lines = [
        "// GENERATED by tools/gen_components.py from tools/kld_tokens.py. DO NOT EDIT BY HAND.",
        "// shadcn/ui-based dark theme (D-05), neutral shadcn primary (D-12). Colors with transparency on the web come pre-mixed over",
        "// background in sRGB: DayZ blends alpha in linear space (lab round 4). 0x00000000 = no color.",
        "class KLD_Tokens",
        "{",
    ]
    for name, c in TOKENS.items():
        lines.append(f"\tstatic const int {name.upper():24} = {argb(c)};")
    lines.append("")
    for variant, (bg, hover, fg, border) in BUTTON.items():
        # DISABLED = opacity-50 of the group over background (shadcn button: disabled:opacity-50), pre-mixed
        for suffix, c in (("BG", bg), ("BG_HOVER", hover), ("FG", fg), ("BORDER", border),
                          ("BG_DISABLED", _disabled(bg)), ("FG_DISABLED", _disabled(fg)), ("BORDER_DISABLED", _disabled(border))):
            lines.append(f"\tstatic const int {('BTN_' + variant + '_' + suffix):24} = {argb(c)};")
    lines.append("")
    for variant, (bg, fg, border) in BADGE.items():
        for suffix, c in (("BG", bg), ("FG", fg), ("BORDER", border)):
            lines.append(f"\tstatic const int {('BADGE_' + variant + '_' + suffix):24} = {argb(c)};")
    lines += ["}", "", "class KLD_Paths", "{"]
    for key, fname in PREFABS.items():
        lines.append(f'\tstatic const string {key:10} = "{PREFIX}/gui/layouts/kld/{fname}";')
    lines += ["}", ""]
    path = CLIENT / "scripts" / "3_Game" / "kld" / "KLD_Tokens.c"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return path


def main():
    print(tokens_c())
    for fn, fname in ((button_layout, PREFABS["BUTTON"]), (lambda: button_layout(BOLD16), PREFABS["BUTTON_PRIMARY"]),
                      (badge_layout, PREFABS["BADGE"]), (lambda: badge_layout(BOLD14), PREFABS["BADGE_PRIMARY"]),
                      (card_layout, PREFABS["CARD"]), (separator_layout, PREFABS["SEPARATOR"])):
        print(write(LAYOUT_DIR / fname, fn()))


if __name__ == "__main__":
    main()
